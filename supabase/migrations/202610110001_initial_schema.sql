create type public.order_source as enum ('customer', 'kiosk');
create type public.receipt_method as enum ('branch_pickup', 'home_delivery');
create type public.order_status as enum (
  'جديد',
  'بانتظار الاستلام',
  'تم الاستلام',
  'تحت المعالجة',
  'جاهز',
  'بالتوصيل',
  'تم التسليم'
);
create type public.app_role as enum ('owner', 'manager', 'worker', 'courier', 'customer');

create table public.services (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table public.item_types (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table public.service_prices (
  item_type_id bigint not null references public.item_types(id),
  service_id bigint not null references public.services(id),
  price numeric(10, 2) not null check (price >= 0),
  primary key (item_type_id, service_id)
);

create table public.workers (
  id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete set null,
  name text not null
);

create table public.couriers (
  id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete set null,
  name text not null
);

create table public.user_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role public.app_role not null,
  worker_id bigint unique references public.workers(id) on delete set null,
  courier_id bigint unique references public.couriers(id) on delete set null,
  check (role <> 'worker' or worker_id is not null),
  check (role <> 'courier' or courier_id is not null)
);

create table public.orders (
  id bigint generated by default as identity primary key,
  source public.order_source not null,
  customer_user_id uuid references auth.users(id) on delete set null,
  customer_name text,
  customer_phone text,
  pickup_address text,
  pickup_at timestamptz,
  receipt_method public.receipt_method not null,
  delivery_address text,
  delivery_at timestamptz,
  courier_id bigint references public.couriers(id) on delete set null,
  status public.order_status not null default 'جديد',
  received_by_worker_id bigint references public.workers(id) on delete set null,
  received_at timestamptz,
  created_at timestamptz not null default now(),
  unique (id, source),
  check (
    source <> 'customer'
    or (
      customer_user_id is not null
      and pickup_address is not null
      and btrim(pickup_address) <> ''
      and pickup_at is not null
    )
  ),
  check (
    (
      receipt_method = 'branch_pickup'
      and delivery_address is null
      and delivery_at is null
    )
    or (
      receipt_method = 'home_delivery'
      and delivery_address is not null
      and btrim(delivery_address) <> ''
      and delivery_at is not null
    )
  ),
  check (
    (received_by_worker_id is null and received_at is null)
    or (received_by_worker_id is not null and received_at is not null)
  ),
  check (
    status in ('جديد', 'بانتظار الاستلام')
    or (received_by_worker_id is not null and received_at is not null)
  )
);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null,
  order_source public.order_source not null,
  item_type_id bigint references public.item_types(id),
  custom_item_name text,
  service_id bigint not null references public.services(id),
  quantity integer not null check (quantity > 0),
  is_urgent boolean not null default false,
  unit_price numeric(10, 2) check (unit_price >= 0),
  foreign key (order_id, order_source) references public.orders(id, source) on delete cascade,
  foreign key (item_type_id, service_id)
    references public.service_prices(item_type_id, service_id),
  check (
    (item_type_id is not null and custom_item_name is null)
    or (
      item_type_id is null
      and custom_item_name is not null
      and btrim(custom_item_name) <> ''
    )
  ),
  check (item_type_id is null or unit_price is not null),
  check (not is_urgent or order_source = 'kiosk')
);

create table public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  status public.order_status not null,
  changed_by_user_id uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now()
);

create or replace function public.current_app_role()
returns public.app_role
language sql
stable
security definer
set search_path = public
as $$
  select role from public.user_profiles where user_id = auth.uid();
$$;

create or replace function public.current_worker_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select worker_id from public.user_profiles where user_id = auth.uid();
$$;

create or replace function public.current_courier_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select courier_id from public.user_profiles where user_id = auth.uid();
$$;

