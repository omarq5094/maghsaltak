create policy "users read own profile"
on public.user_profiles for select
to authenticated
using (user_id = auth.uid());

create policy "authenticated roles read catalog"
on public.services for select
to authenticated
using (public.current_app_role() <> 'courier');

create policy "authenticated roles read item types"
on public.item_types for select
to authenticated
using (public.current_app_role() <> 'courier');

create policy "authenticated roles read service prices"
on public.service_prices for select
to authenticated
using (public.current_app_role() <> 'courier');

create policy "management reads workers"
on public.workers for select
to authenticated
using (public.current_app_role() in ('owner', 'manager'));

create policy "management reads couriers"
on public.couriers for select
to authenticated
using (public.current_app_role() in ('owner', 'manager'));

create policy "roles read allowed orders"
on public.orders for select
to authenticated
using (
  public.current_app_role() in ('owner', 'manager')
  or (public.current_app_role() = 'customer' and customer_user_id = auth.uid())
  or (
    public.current_app_role() = 'worker'
    and status in ('بانتظار الاستلام', 'تم الاستلام', 'تحت المعالجة', 'جاهز')
  )
  or (
    public.current_app_role() = 'courier'
    and courier_id = public.current_courier_id()
  )
);

create policy "roles read allowed order items"
on public.order_items for select
to authenticated
using (
  exists (
    select 1 from public.orders where orders.id = order_items.order_id
  )
);

create policy "roles read allowed order history"
on public.order_status_history for select
to authenticated
using (
  exists (
    select 1 from public.orders where orders.id = order_status_history.order_id
  )
);

create or replace function public.create_order_with_items(
  p_source public.order_source,
  p_customer_user_id uuid,
  p_customer_name text,
  p_customer_phone text,
  p_pickup_address text,
  p_pickup_at timestamptz,
  p_receipt_method public.receipt_method,
  p_delivery_address text,
  p_delivery_at timestamptz,
  p_items jsonb,
  p_created_by uuid
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_order_id bigint;
  item jsonb;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'At least one order item is required';
  end if;

  insert into public.orders (
    source,
    customer_user_id,
    customer_name,
    customer_phone,
    pickup_address,
    pickup_at,
    receipt_method,
    delivery_address,
    delivery_at
  ) values (
    p_source,
    p_customer_user_id,
    p_customer_name,
    p_customer_phone,
    p_pickup_address,
    p_pickup_at,
    p_receipt_method,
    p_delivery_address,
    p_delivery_at
  ) returning id into new_order_id;

  for item in select value from jsonb_array_elements(p_items)
  loop
    insert into public.order_items (
      order_id,
      order_source,
      item_type_id,
      custom_item_name,
      service_id,
      quantity,
      is_urgent,
      unit_price
    ) values (
      new_order_id,
      p_source,
      nullif(item ->> 'itemTypeId', '')::bigint,
      nullif(item ->> 'customItemName', ''),
      (item ->> 'serviceId')::bigint,
      (item ->> 'quantity')::integer,
      coalesce((item ->> 'isUrgent')::boolean, false),
      case
        when nullif(item ->> 'itemTypeId', '') is null then null
        else (
          select sp.price
          from public.service_prices sp
          where sp.item_type_id = (item ->> 'itemTypeId')::bigint
            and sp.service_id = (item ->> 'serviceId')::bigint
        )
      end
    );
  end loop;

  insert into public.order_status_history (order_id, status, changed_by_user_id)
  values (new_order_id, 'جديد', p_created_by);

  return new_order_id;
end;
$$;

create or replace function public.transition_order_status(
  p_order_id bigint,
  p_next_status public.order_status,
  p_changed_by uuid,
  p_received_by_worker_id bigint default null
)
returns setof public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  current_order public.orders%rowtype;
  transition_allowed boolean := false;
begin
  select * into current_order
  from public.orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'Order not found';
  end if;

  transition_allowed := case
    when current_order.status = 'جديد' and p_next_status = 'بانتظار الاستلام' then true
    when current_order.status = 'بانتظار الاستلام' and p_next_status = 'تم الاستلام' then true
    when current_order.status = 'تم الاستلام' and p_next_status = 'تحت المعالجة' then true
    when current_order.status = 'تحت المعالجة' and p_next_status = 'جاهز' then true
    when current_order.status = 'جاهز'
      and current_order.receipt_method = 'branch_pickup'
      and p_next_status = 'تم التسليم' then true
    when current_order.status = 'جاهز'
      and current_order.receipt_method = 'home_delivery'
      and p_next_status = 'بالتوصيل' then true
    when current_order.status = 'بالتوصيل' and p_next_status = 'تم التسليم' then true
    else false
  end;

  if not transition_allowed then
    raise exception 'Status transition is not allowed';
  end if;

  if p_next_status = 'تم الاستلام' and p_received_by_worker_id is null then
    raise exception 'A worker is required to confirm receipt';
  end if;

  update public.orders
  set
    status = p_next_status,
    received_by_worker_id = case
      when p_next_status = 'تم الاستلام' then p_received_by_worker_id
      else received_by_worker_id
    end,
    received_at = case
      when p_next_status = 'تم الاستلام' then now()
      else received_at
    end
  where id = p_order_id;

  insert into public.order_status_history (order_id, status, changed_by_user_id)
  values (p_order_id, p_next_status, p_changed_by);

  return query select * from public.orders where id = p_order_id;
end;
$$;

